SELECT			A.ENTIDADE,
				A.NOME
	FROM		ENTIDADES	A
	LEFT JOIN	TITULOS_PAGAR	B	ON	A.ENTIDADE	=	B.ENTIDADE
	WHERE		B.TITULO_PAGAR	IS	NULL


SELECT			A.ENTIDADE,
				A.NOME
	FROM		ENTIDADES	A
	WHERE		A.ENTIDADE NOT IN (
									SELECT		DISTINCT
												ENTIDADE
										FROM	TITULOS_PAGAR
										)



SELECT			A.ENTIDADE,
				A.NOME,
				B.ESTADO
	FROM		ENTIDADES	A
	JOIN	ENDERECOS	B	ON	A.ENTIDADE	=	B.ENTIDADE
	WHERE		NOT EXISTS (
							SELECT		*
								FROM	TITULOS_PAGAR X
								WHERE	A.ENTIDADE	=	X.ENTIDADE
								)



