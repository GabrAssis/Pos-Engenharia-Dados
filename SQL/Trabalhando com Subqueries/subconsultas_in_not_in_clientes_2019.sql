

-- IN E NOT IN EM SUBQUERY


SELECT		A.ENTIDADE,
			A.NOME,
			B.ESTADO
	FROM	ENTIDADES A
	JOIN ENDERECOS B ON A.ENTIDADE = B.ENTIDADE
	WHERE A.ENTIDADE IN (
		SELECT CLIENTE
		FROM VENDAS_ANALITICAS
		WHERE YEAR (MOVIMENTO) = 2019 )



SELECT		A.ENTIDADE,
			A.NOME,
			B.ESTADO
	FROM	ENTIDADES A
	JOIN ENDERECOS B ON A.ENTIDADE = B.ENTIDADE
	WHERE A.ENTIDADE NOT IN (
		SELECT CLIENTE
		FROM VENDAS_ANALITICAS
		WHERE YEAR (MOVIMENTO) = 2019 )