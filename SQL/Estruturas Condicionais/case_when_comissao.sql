-- AULA: CASE WHEN
-- TIPO: AULA
-- O QUE FAZ: CASE WHEN funciona como um "SE / SENAO" dentro do SQL.
-- Regra usada aqui: venda <= 0 -> sem comissao | 1 a 500 -> 1% |
-- 501 a 10.000 -> 2% | acima de 10.000 -> 3%.

-- Um CASE define o texto da faixa e outro calcula o valor da
-- comissao. O mesmo CASE de calculo se repete no WHERE para
-- filtrar so quem passou de 20.000 de comissao.
SELECT	VENDEDOR,
		VENDA_LIQUIDA,
		CASE	WHEN VENDA_LIQUIDA <= 0						THEN 'SEM COMISSAO' 
				WHEN VENDA_LIQUIDA BETWEEN 1 AND 500		THEN '1%'
				WHEN VENDA_LIQUIDA BETWEEN 501 AND 10000	THEN '2%'
				ELSE '3%'
		END AS COMISSAO,
		CASE	WHEN VENDA_LIQUIDA <= 0						THEN 0.00
				WHEN VENDA_LIQUIDA BETWEEN 1 AND 500		THEN VENDA_LIQUIDA * 0.01
				WHEN VENDA_LIQUIDA BETWEEN 501 AND 10000	THEN VENDA_LIQUIDA * 0.02
				ELSE VENDA_LIQUIDA * 0.03
		END AS VALOR_COMISSAO
FROM	VENDAS_ANALITICAS
WHERE	VENDEDOR IS NOT NULL
	AND	CASE	WHEN VENDA_LIQUIDA <= 0						THEN 0.00
				WHEN VENDA_LIQUIDA BETWEEN 1 AND 500		THEN VENDA_LIQUIDA * 0.01
				WHEN VENDA_LIQUIDA BETWEEN 501 AND 10000	THEN VENDA_LIQUIDA * 0.02
				ELSE VENDA_LIQUIDA * 0.03
		END > 20000;

-- Mesma regra, agora somando as vendas por vendedor num periodo
-- (junta CASE WHEN com GROUP BY e HAVING)
SELECT	VENDEDOR,
		SUM (VENDA_LIQUIDA) AS VENDA_LIQUIDA,
		CASE	WHEN SUM (VENDA_LIQUIDA) <= 0						THEN 'SEM COMISSAO' 
				WHEN SUM (VENDA_LIQUIDA) BETWEEN 1 AND 500			THEN '1%'
				WHEN SUM (VENDA_LIQUIDA) BETWEEN 501 AND 10000		THEN '2%'
		ELSE '3%'
		END AS COMISSAO,
		CASE	WHEN SUM (VENDA_LIQUIDA) <= 0						THEN 0.00
				WHEN SUM (VENDA_LIQUIDA) BETWEEN 1 AND 500			THEN SUM (VENDA_LIQUIDA) * 0.01
				WHEN SUM (VENDA_LIQUIDA) BETWEEN 501 AND 10000		THEN SUM (VENDA_LIQUIDA) * 0.02
				ELSE SUM (VENDA_LIQUIDA) * 0.03
		END AS VALOR_COMISSAO
FROM	VENDAS_ANALITICAS
WHERE	VENDEDOR IS NOT NULL 
	AND MOVIMENTO BETWEEN '01/01/2020' AND '31/01/2020'
GROUP BY VENDEDOR
HAVING	CASE	WHEN SUM (VENDA_LIQUIDA) <= 0						THEN 0.00
				WHEN SUM (VENDA_LIQUIDA) BETWEEN 1 AND 500			THEN SUM (VENDA_LIQUIDA) * 0.01
				WHEN SUM (VENDA_LIQUIDA) BETWEEN 501 AND 10000		THEN SUM (VENDA_LIQUIDA) * 0.02
				ELSE SUM (VENDA_LIQUIDA) * 0.03
		END > 25000
ORDER BY VENDEDOR;
