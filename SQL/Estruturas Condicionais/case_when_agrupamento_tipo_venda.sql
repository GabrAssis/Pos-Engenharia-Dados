
SELECT	TOP 10 QUANTIDADE
FROM VENDAS_ANALITICAS

SELECT	VENDEDOR,
		CAST (AVG (VENDA_LIQUIDA) AS NUMERIC (9,2)) AS MEDIA_VENDAS,
		CASE	WHEN QUANTIDADE < 0 THEN 'DEVOLUÇÃO'
				WHEN OPERACAO_FISCAL IN (12, 14) THEN 'VENDA INTERNA'
				ELSE 'VENDA EXTERNA'		
		END AS TIPO_VENDAS
FROM VENDAS_ANALITICAS
WHERE VENDEDOR = 16 AND YEAR (MOVIMENTO) >= 2020
GROUP BY VENDEDOR, 
		CASE	WHEN QUANTIDADE < 0 THEN 'DEVOLUÇÃO'
				WHEN OPERACAO_FISCAL IN (12, 14) THEN 'VENDA INTERNA'
				ELSE 'VENDA EXTERNA'
		END