
-- INNER JOIN

SELECT *
FROM TableA a
INNER JOIN TableB b
	ON a. KEY = b.KEY

-- LEFT JOIN
-- TRÁS TODA TABELA DA ESQUERDA + INTERSECÇÃO DA DIREITA E OS NULOS

SELECT *
FROM TableA a
LEFT JOIN TableB b
	ON a. KEY = b.KEY


-- SÓ ONDE TABELA B É NULA
SELECT *
FROM TableA a
LEFT JOIN TableB b
	ON a. KEY = b.KEY
WHERE b.KEY IS NULL


-- LEFT JOIN
-- TRÁS TODA TABELA DA DIREITA + INTERSECÇÃO DA ESQUERDA E OS NULOS

SELECT *
FROM TableA a
RIGHT JOIN TableB b
	ON a. KEY = b.KEY


-- SÓ ONDE TABELA B É NULA
SELECT *
FROM TableA a
RIGHT JOIN TableB b
	ON a. KEY = b.KEY
WHERE b.KEY IS NULL

-- FULL JOIN
-- TRÁS TODA TABELA DA DIREITA + INTERSECÇÃO DA ESQUERDA E OS NULOS

SELECT *
FROM TableA a
FULL JOIN TableB b
	ON a. KEY = b.KEY


-- SÓ ONDE TABELA UMA DAS LINHAS É NULA
SELECT *
FROM TableA a
FULL JOIN TableB b
	ON a. KEY = b.KEY
WHERE a.KEY IS NULL
	OR b.KEY IS NULL

