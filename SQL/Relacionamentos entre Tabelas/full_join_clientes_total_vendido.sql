

-- FULL JOIN


SELECT		COALESCE (A.CLIENTE, B.ENTIDADE)	AS	COD_CLIENTE,
			B.NOME								AS	NOME_CLIENTE,
			ISNULL (SUM (A.VENDA_LIQUIDA), 0)	AS	TOTAL_VENDIDO
FROM		VENDAS_ANALITICAS A
FULL JOIN	ENTIDADES B				ON A.CLIENTE = B.ENTIDADE
GROUP BY	A.CLIENTE, B.ENTIDADE,	B.NOME
ORDER BY	TOTAL_VENDIDO DESC



SELECT		TOP 10 *
FROM VENDAS_ANALITICAS A
FULL JOIN ENTIDADES B ON A.CLIENTE = B.ENTIDADE