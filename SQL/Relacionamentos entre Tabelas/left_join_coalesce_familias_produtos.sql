
-- LEFT JOIN É MENOS PERFORMATICO QUE O INNER JOIN, CONSUMINDO MAIS RECURSOS.
-- QUANDO QUEREMOS TRAZER UMA COLUNA QUE ACEITA NULL, VERIFICAR A NECESSIDADE DE UTILIZAR LEFT AO INVÉS DE INNER JOIN

SELECT		A.PRODUTO,
			A.DESCRICAO,
			A.FAMILIA_PRODUTO,
			B.DESCRICAO
	FROM PRODUTOS A
	LEFT JOIN FAMILIAS_PRODUTOS B ON A.FAMILIA_PRODUTO = B.FAMILIA_PRODUTO


SELECT		A.PRODUTO,
			A.DESCRICAO,
			A.FAMILIA_PRODUTO,
			COALESCE (B.DESCRICAO, 'NÃO ENCONTRADO')
	FROM PRODUTOS A
	LEFT JOIN FAMILIAS_PRODUTOS B ON A.FAMILIA_PRODUTO = B.FAMILIA_PRODUTO



SELECT		COUNT(*)
	FROM	PRODUTOS A
	LEFT JOIN GRUPOS_PRODUTOS B ON A.GRUPO_PRODUTO =  B.GRUPO_PRODUTO

SELECT		COUNT(*)
	FROM	PRODUTOS A
	JOIN FAMILIAS_PRODUTOS B ON A.FAMILIA_PRODUTO =  B.FAMILIA_PRODUTO

	
SELECT		COALESCE (C.DESCRICAO, 'NÃO INFORMADA') AS FAMILIA,
			SUM(A.QUANTIDADE)
	FROM	VENDAS_ANALITICAS A
	JOIN	PRODUTOS B ON A.PRODUTO = B.PRODUTO
	LEFT JOIN	FAMILIAS_PRODUTOS C ON  B.FAMILIA_PRODUTO = C.FAMILIA_PRODUTO
	GROUP BY C.DESCRICAO