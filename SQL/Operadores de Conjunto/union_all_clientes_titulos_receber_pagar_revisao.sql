

-- UNION ALL: junta o resultado de duas consultas
-- UNION: junta o resultado distinto de duas consultas (menos performatico que o UNION ALL)

SELECT		'PF'				AS TIPO_CLIENTE,
			ENTIDADE			AS COD_CLIENTE, 
			NOME				AS NOME_CLIENTE, 
			INSCRICAO_FEDERAL	AS INSCRICAO_FEDERAL
	FROM	PESSOAS_FISICAS

UNION ALL

SELECT		'PJ',
			ENTIDADE, 
			NOME, 
			INSCRICAO_FEDERAL
	FROM	PESSOAS_JURIDICAS

UNION ALL

SELECT		'EN',
			ENTIDADE, 
			NOME, 
			INSCRICAO_FEDERAL
	FROM	ENTIDADES

ORDER BY COD_CLIENTE


-- JUNTAR TODOS OS CLIENTES EM UMA MESMA CONSULTA.
-- 1. TODAS CONSULTAS DEVE TER O MESMO N�MERO DE COLUNAS
-- 2. TODOS OS TIPOS DE DADOS DEVEM SER COMPAT�VEIS ENTRE AS COLUNAS
-- 3. ALIAS DAS COLUNAS FICAM NO PRIMEIRO COMANDO SELECT
-- 4. ORDER BY FICA NO ULTIMO COMANDO SELECT

SELECT		B.ENTIDADE			AS COD_CLIENTE, 
			B.NOME				AS NOME_CLIENTE, 
			B.INSCRICAO_FEDERAL	AS INSCRICAO_FEDERAL,
			SUM	(A.VALOR)		AS VALOR_RECEBER,
			0.00				AS VALOR_PAGAR
	FROM	TITULOS_RECEBER	A
	JOIN ENTIDADES			B	ON	A.ENTIDADE	=	B.ENTIDADE
	GROUP BY B.ENTIDADE, B.NOME, B.INSCRICAO_FEDERAL

UNION ALL

SELECT		B.ENTIDADE			AS COD_CLIENTE, 
			B.NOME				AS NOME_CLIENTE, 
			B.INSCRICAO_FEDERAL	AS INSCRICAO_FEDERAL,
			0.00				AS VALOR_RECEBER,
			SUM	(A.VALOR)		AS VALOR_PAGAR
	FROM	TITULOS_PAGAR	A
	JOIN ENTIDADES			B	ON	A.ENTIDADE	=	B.ENTIDADE
	GROUP BY B.ENTIDADE, B.NOME, B.INSCRICAO_FEDERAL

ORDER BY COD_CLIENTE